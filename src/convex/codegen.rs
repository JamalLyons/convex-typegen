//! Emit Serde models from the source-neutral Convex IR.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::ir::{Declared, Function, FunctionKind, GenerationIr, TableDocument, TableShape, Visibility};
use super::utils::{field_ident, function_idents, type_ident};
use super::validator::{ConvexValidator as Validator, Literal};
use crate::error::ConvexTypeGeneratorError;

type Result<T> = std::result::Result<T, ConvexTypeGeneratorError>;

const HEADER: &str = r#"// Generated by convex-typegen — do not edit by hand.

"#;
const MODEL_IMPORTS: &str = r#"#[allow(unused_imports)]
use ::convex_typegen_runtime::{
    model::{Id, RawValue},
    ConvexValue,
    value_serde::Bytes,
};

"#;
const DERIVE: &str = "#[derive(Debug, Clone, ConvexValue)]";

pub(crate) fn generate_code(ir: &GenerationIr) -> Result<String>
{
    let mut emitter = Emitter::default();
    for table in &ir.schema.tables {
        emitter.table(table)?;
    }
    let mut api = ApiModule::default();
    for function in &ir.functions {
        if let (Visibility::Public, Some(path), Some(kind)) =
            (function.visibility, &function.identity.module, kind_name(function.kind))
        {
            let mut module = &mut api;
            for segment in path {
                module = module.children.entry(segment).or_default();
            }
            module.functions.push((function, path, kind));
        }
    }
    let documents = std::mem::take(&mut emitter.code);
    let mut api_code = String::new();
    emitter.api_module("api", &api, 0, &mut api_code)?;

    let mut code = String::from(HEADER);
    code.push_str(MODEL_IMPORTS);
    if !emitter.markers.is_empty() {
        code.push_str("pub mod tables {\n");
        for marker in emitter.markers.keys() {
            writeln!(
                code,
                "    #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n    pub struct {marker};"
            )
            .unwrap();
        }
        code.push_str("}\n\n");
    }
    code.push_str(&documents);
    code.push_str(&api_code);
    Ok(code)
}

#[derive(Default)]
struct ApiModule<'a>
{
    children: BTreeMap<&'a str, Self>,
    functions: Vec<(&'a Function, &'a [String], &'static str)>,
}

fn kind_name(kind: FunctionKind) -> Option<&'static str>
{
    match kind {
        FunctionKind::Query => Some("Query"),
        FunctionKind::Mutation => Some("Mutation"),
        FunctionKind::Action => Some("Action"),
        FunctionKind::Unknown => None,
    }
}

#[derive(Default)]
struct Emitter
{
    code: String,
    names: BTreeMap<String, String>,
    markers: BTreeMap<String, String>,
    marker_origins: BTreeMap<String, String>,
    documents: Vec<(String, Validator)>,
    root_path: String,
}

fn claim(names: &mut BTreeMap<String, String>, name: &str, origin: &str) -> Result<()>
{
    if let Some(previous) = names.insert(name.into(), origin.into()) {
        return Err(ConvexTypeGeneratorError::InvalidSchema {
            context: origin.into(),
            details: format!("Rust identifier collision for `{name}` between {previous} and {origin}"),
        });
    }
    Ok(())
}

fn provenance_context(label: &str, provenance: &super::ir::Provenance) -> String
{
    match provenance.span {
        Some(span) => format!("{label} at {} bytes {}..{}", provenance.source, span.start, span.end),
        None => format!("{label} in {}", provenance.source),
    }
}

impl Emitter
{
    fn marker(&mut self, table: &str, origin: &str) -> Result<String>
    {
        let marker = type_ident(table);
        if let Some(previous) = self.markers.get(&marker) {
            if previous != table {
                return Err(ConvexTypeGeneratorError::InvalidSchema {
                    context: origin.into(),
                    details: format!(
                        "Rust identifier collision for `{marker}` between {} and {origin}",
                        self.marker_origins.get(&marker).map(String::as_str).unwrap_or(previous)
                    ),
                });
            }
        } else {
            self.markers.insert(marker.clone(), table.into());
            self.marker_origins.insert(marker.clone(), origin.into());
        }
        Ok(marker)
    }

    fn table(&mut self, table: &TableDocument) -> Result<()>
    {
        let context = provenance_context(&format!("table {:?}", table.name), &table.provenance);
        let marker = self.marker(&table.name, &context)?;
        let name = format!("{marker}Doc");
        let validator = document_validator(&table.shape, &table.name, &context)?;
        let ty = self.validator(&validator, &name, &context)?;
        self.documents.push((marker.clone(), validator));
        writeln!(
            self.code,
            "impl convex_typegen_runtime::model::Table for tables::{marker} {{\n    type Document = {ty};\n}}\n"
        )
        .unwrap();
        Ok(())
    }

    fn api_module(&mut self, name: &str, module: &ApiModule<'_>, depth: usize, out: &mut String) -> Result<()>
    {
        let indent = "    ".repeat(depth);
        writeln!(out, "{indent}pub mod {name} {{").unwrap();
        self.names.clear();
        self.root_path = "super::".repeat(depth + 1);
        if !module.functions.is_empty() {
            self.code.push_str(MODEL_IMPORTS);
        }
        for (function, path, kind) in &module.functions {
            self.function(function, path, kind)?;
        }
        let body_indent = format!("{indent}    ");
        for line in self.code.trim_end().lines() {
            if !line.is_empty() {
                out.push_str(&body_indent);
            }
            writeln!(out, "{line}").unwrap();
        }
        self.code.clear();

        let mut module_names = BTreeMap::new();
        for (wire, child) in &module.children {
            let ident = field_ident(wire);
            claim(&mut module_names, &ident, &format!("module segment {wire:?}"))?;
            self.api_module(&ident, child, depth + 1, out)?;
        }
        writeln!(out, "{indent}}}").unwrap();
        Ok(())
    }

    fn function(&mut self, function: &Function, module: &[String], kind: &str) -> Result<()>
    {
        let export = &function.identity.export;
        let path = format!("{}:{export}", module.join("/"));
        let (reference, stem) = function_idents(module.last().map_or("", String::as_str), export);
        let context = provenance_context(&format!("function {path:?}"), &function.provenance);
        claim(&mut self.names, &reference, &context)?;

        let args = match &function.args {
            Declared::Declared(fields) => {
                let args = format!("{stem}Args");
                self.object(
                    &args,
                    &format!("{context} args"),
                    fields.iter().map(|field| (field.name.as_str(), &field.validator)),
                )?;
                args
            }
            Declared::Unknown => "::convex_typegen_runtime::function::RawArgs".into(),
        };
        let returns = match &function.returns {
            Declared::Declared(value) => {
                let result = format!("{stem}Return");
                let ty = self.validator(&value.validator, &result, &format!("{context} return"))?;
                if ty != result {
                    claim(&mut self.names, &result, &format!("{context} return"))?;
                    writeln!(self.code, "pub type {result} = {ty};\n").unwrap();
                }
                result
            }
            Declared::Unknown => "RawValue".into(),
        };
        writeln!(
            self.code,
            "#[allow(non_upper_case_globals)]\npub const {reference}: \
             ::convex_typegen_runtime::function::FunctionRef<::convex_typegen_runtime::function::{kind}, {args}, \
             {returns}> =\n    ::convex_typegen_runtime::function::FunctionRef::new({path:?});\n"
        )
        .unwrap();
        Ok(())
    }

    fn validator(&mut self, validator: &Validator, name: &str, context: &str) -> Result<String>
    {
        if let Some((marker, _)) = self.documents.iter().find(|(_, document)| document == validator) {
            return Ok(format!(
                "::convex_typegen_runtime::model::Doc<{}tables::{marker}>",
                self.root_path
            ));
        }
        let primitive = match validator {
            Validator::String | Validator::FunctionHandle(_) => "String",
            Validator::Number => "f64",
            Validator::Boolean => "bool",
            Validator::Null => "()",
            Validator::Int64 => "i64",
            Validator::Bytes => "Bytes",
            Validator::Any | Validator::Object { properties: None } | Validator::Id(None) | Validator::Literal(None) => {
                "RawValue"
            }
            Validator::Id(Some(table)) => {
                let marker = self.marker(table, context)?;
                return Ok(format!("Id<{}tables::{marker}>", self.root_path));
            }
            Validator::Array(element) => {
                let element = self.validator(element, &format!("{name}Element"), &format!("{context} element"))?;
                return Ok(format!("Vec<{element}>"));
            }
            Validator::Record { key_type, value_type } => {
                let key = self.validator(key_type, &format!("{name}Key"), &format!("{context} record key"))?;
                let value = self.validator(value_type, &format!("{name}Value"), &format!("{context} record value"))?;
                return Ok(format!("::std::collections::BTreeMap<{key}, {value}>"));
            }
            Validator::Optional(inner) => {
                let inner = self.validator(inner, name, context)?;
                return Ok(format!("Option<{inner}>"));
            }
            Validator::Object {
                properties: Some(fields),
            } => {
                self.object(
                    name,
                    context,
                    fields.iter().map(|(field, validator)| (field.as_str(), validator)),
                )?;
                return Ok(name.into());
            }
            Validator::Union(branches) => {
                self.union(name, context, branches)?;
                return Ok(name.into());
            }
            Validator::Literal(Some(literal)) => {
                claim(&mut self.names, name, context)?;
                self.literal(name, literal);
                return Ok(name.into());
            }
        };
        Ok(primitive.into())
    }

    fn object<'a>(
        &mut self,
        name: &str,
        context: &str,
        fields: impl IntoIterator<Item = (&'a str, &'a Validator)>,
    ) -> Result<()>
    {
        claim(&mut self.names, name, context)?;
        let mut names = BTreeMap::new();
        let mut body = String::new();
        for (wire, validator) in fields {
            let ident = field_ident(wire);
            let field_context = format!("{context} field {wire:?}");
            claim(&mut names, &ident, &field_context)?;
            let ty = self.validator(validator, &format!("{name}{}", type_ident(wire)), &field_context)?;
            let optional = if matches!(validator, Validator::Optional(_)) {
                ", optional"
            } else {
                ""
            };
            writeln!(body, "    #[convex(rename = {wire:?}{optional})]").unwrap();
            writeln!(body, "    pub {ident}: {ty},").unwrap();
        }
        writeln!(self.code, "{DERIVE}\npub struct {name} {{\n{body}}}\n").unwrap();
        Ok(())
    }

    fn literal(&mut self, name: &str, literal: &Literal)
    {
        let attr = match literal {
            Literal::String(value) => format!("literal = {value:?}"),
            Literal::Boolean(value) => format!("literal = {value}"),
            Literal::Int64(value) => format!("literal = {value}_i64"),
            Literal::Float64(value) => format!("float_bits = {}", value.to_bits()),
        };
        writeln!(
            self.code,
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, ConvexValue)]\n#[convex({attr})]\npub \
             struct {name};\n"
        )
        .unwrap();
    }

    fn union(&mut self, name: &str, context: &str, branches: &[Validator]) -> Result<()>
    {
        claim(&mut self.names, name, context)?;
        let mut variants = String::new();
        let mut leaves = Vec::new();
        flatten_union(branches, &mut leaves);
        let tag = discriminator(&leaves);
        // Only unions used as record keys need Ord. Such unions contain only string-shaped validators.
        let order = if leaves.iter().all(|branch| branch.is_record_key()) {
            ", PartialEq, Eq, PartialOrd, Ord"
        } else {
            ""
        };
        for (i, branch) in leaves.into_iter().enumerate() {
            let variant = format!("Branch{}", i + 1);
            let ty = self.validator(branch, &format!("{name}{variant}"), &format!("{context} {variant}"))?;
            if let Some(tag) = tag {
                let tag_ty = format!("{ty}{}", type_ident(tag));
                writeln!(variants, "    #[convex(tag = {tag_ty})]").unwrap();
            }
            writeln!(variants, "    {variant}({ty}),").unwrap();
        }
        let discriminator = tag.map_or_else(String::new, |tag| format!("#[convex(discriminator = {tag:?})]\n"));
        writeln!(
            self.code,
            "#[derive(Debug, Clone, ConvexValue{order})]\n{discriminator}pub enum {name} {{\n{variants}}}\n"
        )
        .unwrap();
        Ok(())
    }
}

fn document_validator(shape: &TableShape, table: &str, context: &str) -> Result<Validator>
{
    Ok(match shape {
        TableShape::Object(fields) => {
            let mut properties = BTreeMap::from([
                ("_id".into(), Validator::Id(Some(table.into()))),
                ("_creationTime".into(), Validator::Number),
            ]);
            for field in fields {
                if properties.insert(field.name.clone(), field.validator.clone()).is_some() {
                    return Err(ConvexTypeGeneratorError::InvalidSchema {
                        context: context.into(),
                        details: format!("Duplicate document field {:?} (including Convex system fields)", field.name),
                    });
                }
            }
            Validator::Object {
                properties: Some(properties),
            }
        }
        TableShape::Union(branches) => Validator::Union(
            branches
                .iter()
                .map(|branch| document_validator(branch, table, context))
                .collect::<Result<_>>()?,
        ),
    })
}

fn flatten_union<'a>(branches: &'a [Validator], leaves: &mut Vec<&'a Validator>)
{
    for branch in branches {
        match branch {
            Validator::Union(children) => flatten_union(children, leaves),
            branch => leaves.push(branch),
        }
    }
}

fn object_fields(validator: &Validator) -> Option<&BTreeMap<String, Validator>>
{
    match validator {
        Validator::Object { properties } => properties.as_ref(),
        _ => None,
    }
}

/// A required field with a distinct literal in every branch is a safe dispatch key.
fn discriminator<'a>(branches: &[&'a Validator]) -> Option<&'a str>
{
    let first = object_fields(branches.first()?)?;
    first.keys().find_map(|name| {
        let mut seen = Vec::new();
        for branch in branches {
            let Validator::Literal(Some(literal)) = object_fields(branch)?.get(name)? else {
                return None;
            };
            if seen.contains(&literal) {
                return None;
            }
            seen.push(literal);
        }
        Some(name.as_str())
    })
}
